    full_counts = full.get("counts")
    require(isinstance(full_counts, dict), "full source counts missing")
    require(
        full_counts.get("lean_verified_theorem_candidates") == FULL_ROWS
        and full_counts.get("source_screened_candidates") == 2_575
        and full_counts.get("runtime_rejected") == 9
        and full_counts.get("verified_reserve_after_selection") == 0
        and full_counts.get("selected_baseline") == 1_000
        and full_counts.get("selected_dynamic_expansion") == 1_566,
        "full source extraction counts drifted",
    )

    require(manifest.get("release") == "5.5", "parent manifest is not release 5.5")
    catalog_rows = catalog.get("records")
    require(
        isinstance(catalog_rows, list)
        and len(catalog_rows) == 4_525
        and all(isinstance(row, dict) for row in catalog_rows),
        "parent catalog denominator drifted",
    )
    parent_exact, parent_types, parent_names = parent_indexes(catalog_rows)

    # Resolve exact-identity duplicates over all literal theorem rows, using the
    # same winner order as the 5.3 curation.  Literal lemmas remain valid Lean
    # theorems but do not compete for the current release theorem quota.
    source_duplicates: dict[str, dict[str, str]] = {}
    seen_types: dict[str, str] = {}
    seen_names: dict[str, str] = {}
    for row in sorted(
        (item for item in full_rows if item["declaration_kind"] == "theorem"),
        key=duplicate_winner_rank,
    ):
        source_id = str(row["source_record_id"])
        _, norm_type, norm_name = source_identity(row)
        if norm_type in seen_types:
            source_duplicates[source_id] = {
                "source_record_id": seen_types[norm_type],
                "method": "unicode_whitespace_normalized_formal_type",
            }
            continue
        if norm_name in seen_names:
            source_duplicates[source_id] = {
                "source_record_id": seen_names[norm_name],
                "method": "unicode_nfkc_casefolded_declaration_name",
            }
            continue
        seen_types[norm_type] = source_id
        seen_names[norm_name] = source_id
    full_kind_counts = Counter(str(row["declaration_kind"]) for row in full_rows)
    full_exact_types = {str(row["formal_type_sha256"]) for row in full_rows}
    full_normalized_types = {
        normalized_type_sha(str(row["formal_type"])) for row in full_rows
    }
    require(
        len(full_exact_types) == len(full_normalized_types) == 2_561,
        "full-source exact and normalized formal-type identity counts drifted",
    )

    reserve = full_rows[PARENT_SOURCE_ROWS:]
    require(len(reserve) == RESERVE_ROWS, "reserve denominator drifted")
    candidates: list[dict[str, Any]] = []
    for candidate_index, row in enumerate(reserve, 1):
        exact, norm_type, norm_name = source_identity(row)
        parent_conflicts = {
            "exact_formal_type_variant_ids": sorted(parent_exact.get(exact, [])),
            "normalized_formal_type_variant_ids": sorted(parent_types.get(norm_type, [])),
            "normalized_declaration_name_variant_ids": sorted(parent_names.get(norm_name, [])),
        }
        parent_conflict = any(parent_conflicts.values())
        source_duplicate = source_duplicates.get(str(row["source_record_id"]))
        literal_theorem = row["declaration_kind"] == "theorem"
        mechanically_unique = not parent_conflict and source_duplicate is None
        mechanically_eligible = literal_theorem and mechanically_unique
        if mechanically_eligible:
            disposition = "mechanically_eligible_literal_theorem_unique"
        elif not literal_theorem:
            disposition = "literal_lemma_candidate_only_under_current_quota_policy"
        elif parent_conflict:
            disposition = "parent_exact_identity_conflict_candidate_only"
        else:
            disposition = "source_exact_identity_duplicate_candidate_only"
        kinds = signal_kinds(row)
        candidate: dict[str, Any] = {
            "schema_version": SCHEMA,
            "candidate_index": candidate_index,
            "candidate_key": f"mathlib-reserve-v5.6:{row['source_record_id']}",
            "source_index_zero_based": int(row["selection_rank"]) - 1,
            "selection_rank": row["selection_rank"],
            "source_record_id": row["source_record_id"],
            "source_record_sha256": sha(canonical(row)),
            "declaration": row["declaration"],
            "declaration_kind": row["declaration_kind"],
            "source_syntax_kind": row["source_syntax_kind"],
            "formal_type_sha256": exact,
            "normalized_formal_type_sha256": norm_type,
            "normalized_declaration_name_sha256": norm_name,
            "formal_proof_state": row["formal_proof_state"],
            "module": row["source"]["module"],
            "module_root": module_root(row),
            "importance_signal_kinds": list(kinds),
            "has_declaration_docstring": row.get("declaration_docstring") is not None,
            "truth_gate": "kernel_checked_thmInfo_collectAxioms_without_sorryAx_at_pinned_commit",
            "quality_gate": "mathlib_module_main_result_or_docs_1000_signal",
            "identity_review": {
                "parent_5_5": parent_conflicts,
                "source_duplicate_of": source_duplicate,
                "methods": [
                    "exact formal_type_sha256",
                    "Unicode-whitespace normalized formal type",
                    "Unicode NFKC-casefolded full declaration name",
                ],
            },
            "mechanically_unique_under_three_gates": mechanically_unique,
            "mechanically_eligible_for_release_curation": mechanically_eligible,
            "disposition": disposition,
            "candidate_only": True,
            "grants_catalog_entry": False,
            "grants_theorem_credit": False,
            "row_sha256": None,
        }
        candidate["row_sha256"] = hash_without(candidate, "row_sha256")
        candidates.append(candidate)

    # Re-audit the 231 unselected viable literal theorems left by 5.4 against
    # the current 5.5 parent, so the combined next-batch number is not assumed.
    dispositions = curation.get("candidate_dispositions")
    require(isinstance(dispositions, list), "5.4 curation rows missing")
    legacy_ids = {
        str(row["source_record_id"])
        for row in dispositions
        if isinstance(row, dict) and row.get("disposition") == "eligible_not_selected_after_5_4"
    }
    require(len(legacy_ids) == 231, "5.4 residual theorem denominator drifted")
    prefix_by_id = {str(row["source_record_id"]): row for row in prefix_rows}
    legacy_parent_conflicts = 0
    for source_id in sorted(legacy_ids):
        row = prefix_by_id.get(source_id)
        require(row is not None and row.get("declaration_kind") == "theorem", f"legacy residual {source_id} missing")
        exact, norm_type, norm_name = source_identity(row)
