def formal_identity(row: Mapping[str, Any]) -> tuple[str | None, str | None, str | None]:
    formal = row.get("formal_statement")
    formal = formal if isinstance(formal, dict) else {}
    digest = formal.get("formal_type_sha256") or formal.get("declaration_type_sha256") or row.get("formal_type_sha256")
    text = formal.get("formal_type") or formal.get("declaration_type") or row.get("formal_type")
    name = (
        formal.get("declaration")
        or formal.get("qualified_declaration")
        or formal.get("declaration_name")
        or row.get("qualified_name")
    )
    exact = digest if isinstance(digest, str) and SHA_RE.fullmatch(digest) else None
    normalized_type = normalized_type_sha(text) if isinstance(text, str) and text else None
    normalized_name = normalized_name_sha(name) if isinstance(name, str) and name else None
    return exact, normalized_type, normalized_name


def parent_indexes(rows: Sequence[Mapping[str, Any]]) -> tuple[dict[str, list[str]], dict[str, list[str]], dict[str, list[str]]]:
    indexes: tuple[dict[str, list[str]], dict[str, list[str]], dict[str, list[str]]] = (
        defaultdict(list),
        defaultdict(list),
        defaultdict(list),
    )
    for row in rows:
        variant = row.get("variant_id")
        require(isinstance(variant, str) and bool(variant), "parent row lacks variant_id")
        for index, key in zip(indexes, formal_identity(row), strict=True):
            if key is not None:
                index[key].append(variant)
    return indexes


def source_identity(row: Mapping[str, Any]) -> tuple[str, str, str]:
    formal_type = str(row["formal_type"])
    declaration = str(row["declaration"])
    return (
        str(row["formal_type_sha256"]),
        normalized_type_sha(formal_type),
        normalized_name_sha(declaration),
    )


def duplicate_winner_rank(row: Mapping[str, Any]) -> tuple[int, int, str]:
    return (
        0 if "mathlib_1000_theorems" in signal_kinds(row) else 1,
        int(row["selection_rank"]),
        str(row["source_record_id"]),
    )


