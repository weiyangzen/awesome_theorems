    require(isinstance(snapshot, dict), f"{label} source_snapshot missing")
    require(snapshot.get("commit") == SOURCE_COMMIT, f"{label} commit drifted")
    require(snapshot.get("license") == "Apache-2.0", f"{label} license drifted")
    require(snapshot.get("module_cache_complete") is True, f"{label} module cache incomplete")
    require(
        snapshot.get("available_source_modules")
        == snapshot.get("available_ilean_modules")
        == snapshot.get("available_olean_modules")
        == 7_871,
        f"{label} module cache census drifted",
    )
    rows = document.get("records")
    require(
        isinstance(rows, list)
        and len(rows) == rows_expected
        and all(isinstance(row, dict) for row in rows),
        f"{label} must have exactly {rows_expected} object rows",
    )
    seen_ids: set[str] = set()
    seen_names: set[str] = set()
    for index, row in enumerate(rows, 1):
        source_id = row.get("source_record_id")
