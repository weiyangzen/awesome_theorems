        require(isinstance(source_id, str) and bool(source_id), f"{label}[{index}] source id missing")
        require(source_id not in seen_ids, f"{label} duplicates source id {source_id}")
        seen_ids.add(source_id)
        require(row.get("selection_rank") == index, f"{label} ranks are not dense 1..N")
        require(isinstance(declaration, str) and bool(declaration), f"{label}[{index}] declaration missing")
        normalized_declaration = normalize_name(declaration)
        require(normalized_declaration not in seen_names, f"{label} duplicates declaration {declaration}")
        seen_names.add(normalized_declaration)
        kind = row.get("declaration_kind")
