    assert git("rev-parse", "bcf3f9fa79ab8c2b6610c9875668c2589b35b74f:Docs/researches/math_theorems.md") == revisions["repository_source_record_blob"]
    assert git("rev-parse", "16d227cffb7cb7d9e8392b6c0ff8211e498e1330:Docs/Stage1_Targets_rev-5.6.json") == revisions["target_manifest_origin_blob"]
